import type { AoEmojiCategory, AoEmojiItem } from './types';

type Row = [char: string, name: string, ...keywords: string[]];

function rowsToItems(categoryId: string, rows: Row[]): AoEmojiItem[] {
  return rows.map(([char, name, ...keywords]) => ({
    id: char,
    char,
    name,
    keywords: [name, ...keywords].map((k) => k.toLowerCase()),
    categoryId,
    type: 'unicode' as const,
  }));
}

