let _allUnicode: AoEmojiItem[] | null = null;
let _byId: Map<string, AoEmojiItem> | null = null;

export function getUnicodeEmojis(): AoEmojiItem[] {
  if (!_allUnicode) {
    _allUnicode = Object.values(UNICODE_BY_CATEGORY).flat();
  }
  return _allUnicode;
}

export function getUnicodeByCategory(categoryId: string): AoEmojiItem[] {
  return UNICODE_BY_CATEGORY[categoryId] ?? [];
}

export function getEmojiById(id: string): AoEmojiItem | undefined {
  if (!_byId) {
    _byId = new Map(getUnicodeEmojis().map((e) => [e.id, e]));
  }
  return _byId.get(id);
}
