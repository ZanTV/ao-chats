export function searchEmojis(query: string): { category: string; emoji: string }[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const results: { category: string; emoji: string }[] = [];
  for (const cat of EMOJI_CATEGORIES) {
    for (const emoji of cat.emojis) {
      if (cat.label.toLowerCase().includes(q) || emoji.includes(q)) {
        results.push({ category: cat.label, emoji });
      }
    }
  }
  return results;
}
